#!/bin/bash
# One-time setup for the OmaOptions omarchy-shell plugin (andreinita21.omaoptions).
#
# Run it in a terminal (it asks for your sudo password once):
#   bash ~/.config/omarchy/plugins/andreinita21.omaoptions/install.sh
#
# Every step is idempotent — re-run freely. What it does:
#   1. installs solaar (official repo). The engine is Solaar's own listener,
#      run headless as a *user* service; no root daemon, no polkit rule.
#   2. udev rules: Logitech hidraw devices and /dev/uinput usable by you
#      (uinput is what KeyPress / MouseScroll actions need on Wayland)
#   3. removes the logiops setup from earlier versions of this plugin
#      (logid cannot drive the MX Master 3S through a Bolt receiver)
#   4. enables the omaoptions.service user unit
#   5. puts `omaoptions` on PATH and the widget on the bar
#   6. applies the current config

set -uo pipefail

PLUGIN_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
CLI="$PLUGIN_DIR/bin/omaoptions"
DAEMON="$PLUGIN_DIR/bin/omaoptions-daemon"
UNIT_DIR="$HOME/.config/systemd/user"
HYPR_MAIN="$HOME/.config/hypr/hyprland.lua"

c_blue=$'\e[34m' c_green=$'\e[32m' c_yellow=$'\e[33m' c_red=$'\e[31m' c_off=$'\e[0m'
step() { printf '\n%s==> %s%s\n' "$c_blue" "$*" "$c_off"; }
ok()   { printf '  %s✓%s %s\n' "$c_green" "$c_off" "$*"; }
warn() { printf '  %s!%s %s\n' "$c_yellow" "$c_off" "$*"; }
fail() { printf '  %s✗%s %s\n' "$c_red" "$c_off" "$*"; exit 1; }

# ---------------------------------------------------------------- packages
step "Packages"
if command -v solaar >/dev/null; then
  ok "solaar already installed"
else
  sudo pacman -S --needed --noconfirm solaar || fail "could not install solaar"
  ok "solaar installed"
fi
python3 -c "import evdev" 2>/dev/null && ok "python-evdev present (key/scroll simulation)" \
  || { sudo pacman -S --needed --noconfirm python-evdev && ok "python-evdev installed"; }

# ---------------------------------------------------------------- udev
step "Device permissions (udev)"
sudo rm -f /etc/udev/rules.d/70-omarchy-logi.rules /etc/modules-load.d/omarchy-logi.conf
sudo tee /etc/udev/rules.d/70-omaoptions.rules >/dev/null <<'EOF'
# Installed by the OmaOptions Omarchy plugin.
# Let the logged-in user talk HID++ to Logitech devices over any transport.
KERNEL=="hidraw*", SUBSYSTEM=="hidraw", ATTRS{idVendor}=="046d", TAG+="uaccess"
KERNEL=="hidraw*", SUBSYSTEM=="hidraw", KERNELS=="0005:046D:*", TAG+="uaccess"
# Simulated key presses / scrolling (Solaar rules on Wayland) go through uinput.
KERNEL=="uinput", SUBSYSTEM=="misc", TAG+="uaccess", OPTIONS+="static_node=uinput"
EOF
echo uinput | sudo tee /etc/modules-load.d/omaoptions.conf >/dev/null
sudo modprobe uinput
sudo udevadm control --reload
sudo udevadm trigger --subsystem-match=hidraw --subsystem-match=misc --action=add
sleep 1
[[ -w /dev/uinput ]] && ok "/dev/uinput writable" || warn "/dev/uinput not writable yet — log out and back in once"
readable=0
for h in /dev/hidraw*; do [[ -r $h && -w $h ]] && readable=$((readable + 1)); done
ok "$readable hidraw device(s) accessible to $USER"

# ---------------------------------------------------------------- remove logiops leftovers
step "Retire logiops"
systemctl --user disable --now logid.service >/dev/null 2>&1 || true
rm -f "$UNIT_DIR/logid.service"
if systemctl list-unit-files logid.service >/dev/null 2>&1; then
  sudo systemctl disable --now logid.service >/dev/null 2>&1 || true
  sudo systemctl mask logid.service >/dev/null 2>&1 || true
fi
sudo rm -rf /etc/systemd/system/logid.service.d /etc/polkit-1/rules.d/50-omaoptions-logid.rules
sudo systemctl daemon-reload
rm -f "$HOME/.config/hypr/omaoptions.lua" "$HOME/.config/hypr/logi.lua" "$HOME/.config/omarchy/omaoptions/logid.cfg"
if grep -q 'hypr.omaoptions\|hypr.logi' "$HYPR_MAIN" 2>/dev/null; then
  sed -i '/Logitech MX bindings generated by the .*plugin/d; /module("hypr.omaoptions")/d; /module("hypr.logi")/d' "$HYPR_MAIN"
  ok "removed the old Hyprland hook (virtual keys are no longer needed)"
fi
ok "logid stopped, disabled and masked (package left installed)"

# ---------------------------------------------------------------- engine service
step "OmaOptions engine (user service)"
mkdir -p "$UNIT_DIR"
cat > "$UNIT_DIR/omaoptions.service" <<EOF
[Unit]
Description=OmaOptions engine (headless Solaar) for Logitech MX devices
After=graphical-session.target
PartOf=graphical-session.target

[Service]
ExecStart=/usr/bin/python3 $DAEMON
Restart=on-failure
RestartSec=3

[Install]
WantedBy=graphical-session.target
EOF
systemctl --user daemon-reload
systemctl --user enable omaoptions.service >/dev/null 2>&1
ok "omaoptions.service enabled"

# ---------------------------------------------------------------- CLI + bar
step "CLI and bar widget"
mkdir -p "$HOME/.local/bin"
rm -f "$HOME/.local/bin/omarchy-logi"
ln -sfn "$CLI" "$HOME/.local/bin/omaoptions"
ok "~/.local/bin/omaoptions -> plugin"
if grep -q '"andreinita21.omaoptions"' "$HOME/.config/omarchy/shell.json" 2>/dev/null; then
  ok "widget already on the bar"
else
  omarchy-bar put andreinita21.omaoptions --before omarchy.bluetooth >/dev/null 2>&1 || omarchy-bar put andreinita21.omaoptions >/dev/null 2>&1 \
    && ok "widget added to the bar" || warn "could not add the widget automatically; run: omarchy bar put andreinita21.omaoptions"
fi

# ---------------------------------------------------------------- apply
step "Apply configuration"
"$CLI" apply | python3 -c '
import json, sys
d = json.load(sys.stdin)
for n in d.get("notes", []): print("  ✓ " + n)
for w in d.get("warnings", []): print("  ! " + w)
'
sleep 2
if systemctl --user is-active --quiet omaoptions.service; then
  ok "engine running"
  "$CLI" status | python3 -c '
import json, sys
d = json.load(sys.stdin)
for dev in d.get("devices", []):
    print("  - %s: %s%s" % (dev["name"], "online" if dev["connected"] else "offline", (", %s%%" % dev["battery"]) if dev.get("battery") is not None else ""))
'
else
  warn "engine not running — see: journalctl --user -u omaoptions -n 30"
fi

printf '\n%sDone.%s Click the mouse icon in the bar to configure. Diagnostics: omaoptions doctor\n' "$c_green" "$c_off"
